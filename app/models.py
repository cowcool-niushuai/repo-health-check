"""Pydantic data models for repository health check requests and reports."""

from typing import Literal, Optional
from pydantic import BaseModel, Field


class ScanRequest(BaseModel):
    """Incoming scan request payload."""

    repo_url: str = Field(..., min_length=1, max_length=2048, description="Public Git repository HTTPS URL")
    llm_api_key: Optional[str] = Field(default=None, max_length=512, description="Optional OpenAI-compatible API key")
    llm_base_url: Optional[str] = Field(default=None, max_length=2048, description="Optional OpenAI-compatible base URL")
    llm_model: Optional[str] = Field(default=None, max_length=200, description="Optional LLM model name")


class RiskItem(BaseModel):
    """Single detected onboarding risk."""

    category: Literal["completeness", "windows_script", "hardcoded_path", "secret"]
    severity: Literal["high", "medium", "low"]
    title: str
    file: str
    line: Optional[int] = None
    snippet: Optional[str] = None
    suggestion: str


class CompletenessDetail(BaseModel):
    """Repository completeness inspection results."""

    has_readme: bool
    readme_files: list[str] = Field(default_factory=list)
    readme_sections: dict[str, bool] = Field(default_factory=dict)
    has_dependencies: bool
    dependency_files: list[str] = Field(default_factory=list)
    has_startup: bool
    startup_files: list[str] = Field(default_factory=list)


class ScoreBreakdown(BaseModel):
    """Explainable readiness score and per-dimension ratings."""

    overall_score: int
    grade: Literal["A", "B", "C", "D"]
    dimension_scores: dict[str, int]
    deductions: list[str] = Field(default_factory=list)


class AIAdvice(BaseModel):
    """Onboarding recommendations generated by LLM or rule-based fallback."""

    source: Literal["llm", "rule_engine"]
    ai_score: Optional[int] = None
    summary: str
    recommended_commands: list[str] = Field(default_factory=list)
    top_actions: list[str] = Field(default_factory=list)
    error_note: Optional[str] = None


class RepoMeta(BaseModel):
    """Metadata of the scanned repository snapshot."""

    repo_url: str
    repo_name: str
    branch: str
    commit_sha: str
    short_sha: str
    scanned_at: str
    files_scanned: int


class ScanReport(BaseModel):
    """Complete repository health check report."""

    meta: RepoMeta
    completeness: CompletenessDetail
    score: ScoreBreakdown
    risks: list[RiskItem] = Field(default_factory=list)
    risk_counts: dict[str, int] = Field(default_factory=dict)
    ai_advice: AIAdvice
